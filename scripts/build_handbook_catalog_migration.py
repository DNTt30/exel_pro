"""Build a deterministic, reviewable SQL import from the archived source catalog.
No network/database access. This never approves documents on behalf of Admin.
"""
from pathlib import Path
import json

root = Path(__file__).resolve().parents[1]
catalog = json.loads((root/'scripts/data/handbook-catalog.json').read_text(encoding='utf-8'))
payload = json.dumps(catalog, ensure_ascii=False).replace("'", "''")
body = """-- Generated by scripts/build_handbook_catalog_migration.py. Import to pending review only.
-- Requires 20261017000000_handbook_publication and 20261018000000_handbook_catalog.
BEGIN;
CREATE TABLE IF NOT EXISTS public.handbook_catalog_imports (
 source_key text PRIMARY KEY, entry_id uuid REFERENCES public.handbook_entries(id),
 outcome text NOT NULL, imported_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.handbook_catalog_imports ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.handbook_catalog_imports FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.handbook_catalog_imports TO authenticated;
DROP POLICY IF EXISTS handbook_import_admin ON public.handbook_catalog_imports;
CREATE POLICY handbook_import_admin ON public.handbook_catalog_imports FOR SELECT TO authenticated USING(public.is_admin());
DO $import$
DECLARE item jsonb; existing uuid; matches integer; imported uuid; body jsonb;
BEGIN
 PERFORM pg_advisory_xact_lock(hashtextextended('handbook-catalog-import-v1',0));
 FOR item IN SELECT value FROM jsonb_array_elements('__CATALOG__'::jsonb) LOOP
  IF EXISTS(SELECT 1 FROM public.handbook_catalog_imports WHERE source_key=item->>'key') THEN CONTINUE; END IF;
  -- Never overwrite an approved/archived/local-edited document or duplicate its pending proposal.
  SELECT count(*),min(id::text)::uuid INTO matches,existing FROM public.handbook_entries
   WHERE store_id IS NULL AND lower(trim(title))=lower(trim(item->>'title'));
  IF matches>0 THEN
   INSERT INTO public.handbook_catalog_imports(source_key,entry_id,outcome)
   VALUES(item->>'key',CASE WHEN matches=1 THEN existing ELSE NULL END,CASE WHEN matches=1 THEN 'existing_preserved' ELSE 'ambiguous_preserved' END);
   CONTINUE;
  END IF;
  imported:=(item->>'id')::uuid;
  body:=(item-'key'-'id');
  INSERT INTO public.handbook_entries(id,title,content,category,source_doc,created_by,is_active,aliases)
   VALUES(imported,item->>'title',item->>'content',item->>'category',item->>'source_doc','catalog-import',false,
    ARRAY(SELECT jsonb_array_elements_text(item->'aliases')));
  INSERT INTO public.handbook_changes(entry_id,base_revision,operation,payload,submitted_by,confirmed_at)
   VALUES(imported,1,'upsert',body,'catalog-import',NULL);
  INSERT INTO public.handbook_catalog_imports(source_key,entry_id,outcome) VALUES(item->>'key',imported,'pending_review');
 END LOOP;
END $import$;
COMMIT;
""".replace('__CATALOG__',payload)
(root/'supabase/migrations/20261018000001_handbook_catalog_seed.sql').write_text(body,encoding='utf-8')
print(f'Generated pending import: {len(catalog)} records; no automatic publication.')
